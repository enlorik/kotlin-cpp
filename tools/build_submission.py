#!/usr/bin/env python3
"""Generate a single Kotlin contest submission from selected library modules.

This is a source bundler, not a dependency inference engine. Each named module
has an explicit, CI-tested list of source dependencies. Kotlin files in this
repository share the default package; imports are moved to the beginning of
the generated file. No compiler, network access, or third-party Python package
is required to generate the output.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]

# Keep groups explicit: a misleading "auto-resolved" missing dependency can
# produce an invalid submission at the worst possible moment (during a contest).
MODULES: dict[str, tuple[str, ...]] = {
    "fast-io": ("io/FastIO.kt",),
    "binary-search": ("search/BinarySearch.kt",),
    "advanced-binary-search": (
        "search/BinarySearch.kt",
        "search/AdvancedBinarySearch.kt",
    ),
    "segment-tree": (
        "shared/AggregationOp.kt",
        "tree/SegmentTree.kt",
        "shared/SegmentTreeAggregations.kt",
    ),
    "sum-segment-tree": ("tree/LongSumSegmentTree.kt",),
    "grid-bfs": ("grid/GridBfs.kt",),
    "graph": (
        "graph/GraphTypes.kt",
        "graph/GraphResults.kt",
        "graph/SparseGraph.kt",
        "graph/AutoShortestPaths.kt",
    ),
    "range-index": (
        "shared/AggregationOp.kt",
        "shared/CustomAlgebra.kt",
        "shared/TypedAlgebra.kt",
        "shared/TypedAlgebraBridge.kt",
        "tree/SegmentTree.kt",
        "shared/SegmentTreeAggregations.kt",
        "range/SparseTables.kt",
        "tree/ConfigurableLazySegmentTree.kt",
        "tree/PersistentAggregateTree.kt",
        "tree/TypedAlgebraTrees.kt",
        "tree/AssignmentLazyTree.kt",
        "range/RangeIndex.kt",
    ),
}

IMPORT_RE = re.compile(r"^import\s+.+$", re.MULTILINE)
PACKAGE_RE = re.compile(r"^\s*package\s+\S+", re.MULTILINE)
FILE_ANNOTATION_RE = re.compile(r"^\s*@file:", re.MULTILINE)


def selected_files(names: list[str]) -> list[str]:
    """Expand module names in first-use order and remove repeated sources."""
    if not names:
        raise ValueError("Select at least one module; use --list to see options")
    result: list[str] = []
    seen: set[str] = set()
    for name in names:
        if name not in MODULES:
            raise ValueError(
                f"Unknown module {name!r}. Choose from: {', '.join(sorted(MODULES))}"
            )
        for path in MODULES[name]:
            if path not in seen:
                seen.add(path)
                result.append(path)
    return result


def split_source(text: str, label: str) -> tuple[list[str], str]:
    """Hoist Kotlin imports, while rejecting syntax unsafe to flatten."""
    if PACKAGE_RE.search(text):
        raise ValueError(f"{label}: packaged Kotlin sources cannot be bundled")
    if FILE_ANNOTATION_RE.search(text):
        raise ValueError(f"{label}: @file annotations cannot be bundled safely")
    imports = IMPORT_RE.findall(text)
    body = IMPORT_RE.sub("", text).strip()
    return imports, body


def render(
    root: Path, modules: list[str], solution: Path | None = None
) -> tuple[str, list[Path]]:
    """Return deterministic Kotlin text and the input paths used to build it."""
    sources = selected_files(modules)
    files = [(label, root / label) for label in sources]
    if solution is not None:
        files.append(("solution", solution))

    all_imports: list[str] = []
    seen_imports: set[str] = set()
    chunks: list[str] = []
    for label, path in files:
        if not path.is_file():
            raise ValueError(f"Missing source file: {path}")
        imports, body = split_source(path.read_text(encoding="utf-8"), label)
        for item in imports:
            if item not in seen_imports:
                seen_imports.add(item)
                all_imports.append(item)
        chunks.append(f"// ===== {label} =====\n{body}")

    header = (
        "// Generated by tools/build_submission.py; do not edit the library copy.\n"
        f"// Modules: {', '.join(modules)}\n"
        f"// Sources: {', '.join(sources)}\n"
    )
    output = header + "\n"
    if all_imports:
        output += "\n".join(all_imports) + "\n\n"
    output += "\n\n".join(chunks) + "\n"
    return output, [path for _, path in files]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--modules",
        action="append",
        help="Comma-separated modules, repeatable (e.g. fast-io,binary-search)",
    )
    parser.add_argument("--solution", type=Path, help="Your Kotlin main() file")
    parser.add_argument("--output", type=Path, help="Generated standalone .kt file")
    parser.add_argument(
        "--list", action="store_true", help="List supported modules and exit"
    )
    args = parser.parse_args(argv)
    if args.list:
        for name in sorted(MODULES):
            print(f"{name:24} {', '.join(MODULES[name])}")
        return 0

    if not args.modules or args.output is None:
        parser.error("--modules and --output are required unless --list is used")
    modules = [
        item.strip()
        for group in args.modules
        for item in group.split(",")
        if item.strip()
    ]
    try:
        result, inputs = render(ROOT, modules, args.solution)
        output = args.output.resolve()
        if any(output == path.resolve() for path in inputs):
            raise ValueError("Output would overwrite a source or solution file")
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(result, encoding="utf-8")
    except (ValueError, OSError) as exc:
        parser.error(str(exc))

    print(f"Wrote {output} ({len(inputs)} source files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
